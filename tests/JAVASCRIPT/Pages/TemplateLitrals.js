//What are template literals?
//Normally, we create strings using single quotes (' ') or double quotes (" ").
let name = "Arun";
//Here, we use the + operator to combine the string and variable.
console.log("hellow "+ name )//Arun

//Template literals provide an easier way.
console.log(`Hellow ${name}`)///We use backticks ` ` instead of single or double quotes.
                    //We use ${} to insert a variable inside the string.